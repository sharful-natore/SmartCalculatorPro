// TAB 6: AUDIO LETTER QUIZ (শুনে হরফ বাছাই)
// =========================================================================
@Composable
fun AudioLetterQuizTab(
    themeColors: CalculatorThemeColors,
    isBn: Boolean,
    ttsPlayer: IslamicMaleTtsPlayer,
    primaryGreen: Color
) {
    val allLetters = QuranLearningData.ARABIC_LETTERS
    var currentRound by remember { mutableIntStateOf(1) }
    var score by remember { mutableIntStateOf(0) }
    var selectedOption by remember { mutableStateOf<ArabicLetter?>(null) }
    var isAnswered by remember { mutableStateOf(false) }
    var isSequentialOrder by remember { mutableStateOf(false) }

    val targetLetter = remember(currentRound, isSequentialOrder) {
        if (isSequentialOrder) {
            allLetters[(currentRound - 1) % allLetters.size]
        } else {
            allLetters.shuffled(java.util.Random(currentRound.toLong() * 37L + score)).first()
        }
    }

    val options = remember(currentRound, isSequentialOrder) {
        val distractors = allLetters.filter { it.id != targetLetter.id }.shuffled().take(3)
        (distractors + targetLetter).shuffled()
    }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(16.dp),
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        // TOP SCORE BANNER & ORDER SELECTOR
        Column(modifier = Modifier.fillMaxWidth()) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = if (isBn) "অডিও কুইজ: রাউন্ড $currentRound" else "Audio Quiz: Round $currentRound",
                    fontSize = 15.sp,
                    fontWeight = FontWeight.Bold,
                    color = themeColors.displayText
                )

                Surface(
                    shape = RoundedCornerShape(12.dp),
                    color = primaryGreen.copy(alpha = 0.15f)
                ) {
                    Text(
                        text = if (isBn) "স্কোর: $score পয়েন্ট" else "Score: $score pts",
                        fontSize = 12.5.sp,
                        fontWeight = FontWeight.Bold,
                        color = primaryGreen,
                        modifier = Modifier.padding(horizontal = 10.dp, vertical = 4.dp)
                    )
                }
            }

            Spacer(modifier = Modifier.height(10.dp))

            // MODE TOGGLE CHIPS (Random vs Sequential)
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.Center,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Surface(
                    shape = RoundedCornerShape(12.dp),
                    color = if (!isSequentialOrder) primaryGreen else themeColors.cardBg,
                    border = BorderStroke(1.dp, if (!isSequentialOrder) primaryGreen else themeColors.displayText.copy(alpha = 0.15f)),
                    shadowElevation = if (!isSequentialOrder) 2.dp else 0.dp,
                    modifier = Modifier
                        .clip(RoundedCornerShape(12.dp))
                        .clickable {
                            isSequentialOrder = false
                            selectedOption = null
                            isAnswered = false
                        }
                ) {
                    Row(
                        modifier = Modifier.padding(horizontal = 12.dp, vertical = 6.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Icon(
                            imageVector = Icons.Default.Shuffle,
                            contentDescription = null,
                            tint = if (!isSequentialOrder) Color.White else themeColors.displayText,
                            modifier = Modifier.size(14.dp)
                        )
                        Spacer(modifier = Modifier.width(5.dp))
                        Text(
                            text = if (isBn) "এলোমেলো প্র্যাকটিস" else "Random Practice",
                            fontSize = 11.5.sp,
                            fontWeight = if (!isSequentialOrder) FontWeight.Bold else FontWeight.Medium,
                            color = if (!isSequentialOrder) Color.White else themeColors.displayText
                        )
                    }
                }

                Spacer(modifier = Modifier.width(8.dp))

                Surface(
                    shape = RoundedCornerShape(12.dp),
                    color = if (isSequentialOrder) primaryGreen else themeColors.cardBg,
                    border = BorderStroke(1.dp, if (isSequentialOrder) primaryGreen else themeColors.displayText.copy(alpha = 0.15f)),
                    shadowElevation = if (isSequentialOrder) 2.dp else 0.dp,
                    modifier = Modifier
                        .clip(RoundedCornerShape(12.dp))
                        .clickable {
                            isSequentialOrder = true
                            selectedOption = null
                            isAnswered = false
                        }
                ) {
                    Row(
                        modifier = Modifier.padding(horizontal = 12.dp, vertical = 6.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Icon(
                            imageVector = Icons.Default.FormatListBulleted,
                            contentDescription = null,
                            tint = if (isSequentialOrder) Color.White else themeColors.displayText,
                            modifier = Modifier.size(14.dp)
                        )
                        Spacer(modifier = Modifier.width(5.dp))
                        Text(
                            text = if (isBn) "সিরিয়াল অনুযায়ী" else "Sequential Order",
                            fontSize = 11.5.sp,
                            fontWeight = if (isSequentialOrder) FontWeight.Bold else FontWeight.Medium,
                            color = if (isSequentialOrder) Color.White else themeColors.displayText
                        )
                    }
                }
            }
        }

        Spacer(modifier = Modifier.height(14.dp))

        // SPEAKER CARD
        Surface(
            shape = RoundedCornerShape(22.dp),
            color = themeColors.cardBg,
            border = BorderStroke(1.5.dp, primaryGreen.copy(alpha = 0.4f)),
            shadowElevation = 3.dp,
            modifier = Modifier
                .fillMaxWidth()
                .clip(RoundedCornerShape(22.dp))
                .clickable {
                    ttsPlayer.speakFastArabic("audio_quiz_${targetLetter.id}", targetLetter.arabic)
                }
        ) {
            Column(
                modifier = Modifier.padding(20.dp),
                horizontalAlignment = Alignment.CenterHorizontally
            ) {
                Box(
                    modifier = Modifier
                        .size(68.dp)
                        .clip(CircleShape)
                        .background(primaryGreen.copy(alpha = 0.15f)),
                    contentAlignment = Alignment.Center
                ) {
                    Icon(
                        imageVector = Icons.AutoMirrored.Filled.VolumeUp,
                        contentDescription = "Play Audio",
                        tint = primaryGreen,
                        modifier = Modifier.size(36.dp)
                    )
                }

                Spacer(modifier = Modifier.height(12.dp))

                Text(
                    text = if (isBn) "উচ্চারণটি শুনুন এবং সঠিক হরফটি বাছাই করুন" else "Listen to the audio and pick the correct letter",
                    fontSize = 13.5.sp,
                    fontWeight = FontWeight.Bold,
                    color = themeColors.displayText,
                    textAlign = TextAlign.Center
                )

                Spacer(modifier = Modifier.height(4.dp))

                Text(
                    text = if (isBn) "(পুনরায় উচ্চারণ শুনতে এখানে ট্যাপ করুন)" else "(Tap here to replay audio)",
                    fontSize = 11.sp,
                    color = primaryGreen,
                    fontWeight = FontWeight.Medium
                )
            }
        }

        Spacer(modifier = Modifier.height(18.dp))

        Text(
            text = if (isBn) "নিচের ৪টি হরফ থেকে সঠিকটি সিলেক্ট করুন:" else "Select the correct letter from options:",
            fontSize = 13.sp,
            fontWeight = FontWeight.SemiBold,
            color = themeColors.displayText.copy(alpha = 0.8f),
            modifier = Modifier.fillMaxWidth()
        )

        Spacer(modifier = Modifier.height(12.dp))

        // 2x2 GRID OF OPTIONS
        Column(
            verticalArrangement = Arrangement.spacedBy(12.dp),
            modifier = Modifier.fillMaxWidth()
        ) {
            options.chunked(2).forEach { rowItems ->
                Row(
                    horizontalArrangement = Arrangement.spacedBy(12.dp),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    rowItems.forEach { option ->
                        val isCorrect = option.id == targetLetter.id
                        val isSelected = selectedOption?.id == option.id

                        val cardBg = when {
                            isAnswered && isCorrect -> Color(0xFF059669).copy(alpha = 0.2f)
                            isAnswered && isSelected && !isCorrect -> Color(0xFFDC2626).copy(alpha = 0.2f)
                            isSelected -> primaryGreen.copy(alpha = 0.12f)
                            else -> themeColors.cardBg
                        }

                        val borderColor = when {
                            isAnswered && isCorrect -> Color(0xFF059669)
                            isAnswered && isSelected && !isCorrect -> Color(0xFFDC2626)
                            isSelected -> primaryGreen
                            else -> themeColors.displayText.copy(alpha = 0.15f)
                        }

                        Surface(
                            shape = RoundedCornerShape(18.dp),
                            color = cardBg,
                            border = BorderStroke(1.5.dp, borderColor),
                            shadowElevation = 2.dp,
                            modifier = Modifier
                                .weight(1f)
                                .height(95.dp)
                                .clip(RoundedCornerShape(18.dp))
                                .clickable(enabled = !isAnswered) {
                                    selectedOption = option
                                    isAnswered = true
                                    if (isCorrect) {
                                        score += 10
                                    }
                                }
                        ) {
                            Column(
                                modifier = Modifier.fillMaxSize(),
                                horizontalAlignment = Alignment.CenterHorizontally,
                                verticalArrangement = Arrangement.Center
                            ) {
                                Text(
                                    text = option.arabic,
                                    fontSize = 38.sp,
                                    fontWeight = FontWeight.Bold,
                                    color = if (isAnswered && isCorrect) Color(0xFF059669) else primaryGreen
                                )
                                if (isAnswered) {
                                    Spacer(modifier = Modifier.height(2.dp))
                                    Text(
                                        text = option.banglaName,
                                        fontSize = 11.5.sp,
                                        fontWeight = FontWeight.Bold,
                                        color = themeColors.displayText
                                    )
                                }
                            }
                        }
                    }
                }
            }
        }

        if (isAnswered) {
            Spacer(modifier = Modifier.height(16.dp))

            val isCorrectAnswer = selectedOption?.id == targetLetter.id
            Surface(
                shape = RoundedCornerShape(14.dp),
                color = if (isCorrectAnswer) Color(0xFF059669).copy(alpha = 0.12f) else Color(0xFFDC2626).copy(alpha = 0.12f),
                border = BorderStroke(1.dp, if (isCorrectAnswer) Color(0xFF059669) else Color(0xFFDC2626)),
                modifier = Modifier.fillMaxWidth()
            ) {
                Row(
                    modifier = Modifier.padding(14.dp),
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Icon(
                        imageVector = if (isCorrectAnswer) Icons.Default.CheckCircle else Icons.Default.Cancel,
                        contentDescription = null,
                        tint = if (isCorrectAnswer) Color(0xFF059669) else Color(0xFFDC2626),
                        modifier = Modifier.size(24.dp)
                    )
                    Spacer(modifier = Modifier.width(10.dp))
                    Column {
                        Text(
                            text = if (isCorrectAnswer) "মাশাল্লাহ! সঠিক উত্তর" else "ভুল উত্তর! সঠিক হরফ: ${targetLetter.arabic} (${targetLetter.banglaName})",
                            fontSize = 13.5.sp,
                            fontWeight = FontWeight.Bold,
                            color = themeColors.displayText
                        )
                        Text(
                            text = "মাখরাজ: ${targetLetter.makhrajBn}",
                            fontSize = 11.5.sp,
                            color = themeColors.displayText.copy(alpha = 0.75f)
                        )
                    }
                }
            }

            Spacer(modifier = Modifier.height(16.dp))

            Button(
                onClick = {
                    currentRound += 1
                    selectedOption = null
                    isAnswered = false
                },
                colors = ButtonDefaults.buttonColors(containerColor = primaryGreen),
                modifier = Modifier.fillMaxWidth(),
                shape = RoundedCornerShape(14.dp)
            ) {
                Text(text = if (isBn) "পরবর্তী রাউন্ড →" else "Next Round →", fontSize = 14.sp, fontWeight = FontWeight.Bold)
            }
        }
    }
}

// =========================================================================
// TAB 7: QURAN LEARNING QUIZ TEST (SCROLLABLE, 10 QUESTIONS PER SESSION)
// =========================================================================
@Composable
fun QuizTab(
    themeColors: CalculatorThemeColors,
    isBn: Boolean,
    primaryGreen: Color
) {
    val allQuestions = QuranLearningData.QUIZ_QUESTIONS
    var sessionSeed by remember { mutableIntStateOf(0) }

    // Select 10 random questions per quiz session
    val sessionQuestions = remember(sessionSeed) {
        allQuestions.shuffled(kotlin.random.Random(sessionSeed)).take(10)
    }

    var currentIndex by remember { mutableIntStateOf(0) }
    var score by remember { mutableIntStateOf(0) }
    var correctCount by remember { mutableIntStateOf(0) }
    var selectedIndex by remember { mutableStateOf<Int?>(null) }
    var isSubmitted by remember { mutableStateOf(false) }

    val currentQ = sessionQuestions.getOrNull(currentIndex)

    Column(
        modifier = Modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(16.dp),
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        if (currentQ != null && currentIndex < sessionQuestions.size) {
            // SCORE & PROGRESS BAR
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = if (isBn) "প্রশ্ন ${currentIndex + 1} / ${sessionQuestions.size}" else "Question ${currentIndex + 1} / ${sessionQuestions.size}",
                    fontSize = 14.sp,
                    fontWeight = FontWeight.Bold,
                    color = themeColors.displayText
                )

                Surface(
                    shape = RoundedCornerShape(12.dp),
                    color = primaryGreen.copy(alpha = 0.15f)
                ) {
                    Text(
                        text = if (isBn) "স্কোর: $score পয়েন্ট" else "Score: $score pts",
                        fontSize = 12.5.sp,
                        fontWeight = FontWeight.Bold,
                        color = primaryGreen,
                        modifier = Modifier.padding(horizontal = 10.dp, vertical = 4.dp)
                    )
                }
            }

            Spacer(modifier = Modifier.height(8.dp))

            LinearProgressIndicator(
                progress = { (currentIndex + 1).toFloat() / sessionQuestions.size.toFloat() },
                modifier = Modifier
                    .fillMaxWidth()
                    .height(6.dp)
                    .clip(RoundedCornerShape(3.dp)),
                color = primaryGreen,
                trackColor = primaryGreen.copy(alpha = 0.15f)
            )

            Spacer(modifier = Modifier.height(16.dp))

            // QUESTION CARD
            Surface(
                shape = RoundedCornerShape(20.dp),
                color = themeColors.cardBg,
                border = BorderStroke(1.dp, primaryGreen.copy(alpha = 0.3f)),
                shadowElevation = 3.dp,
                modifier = Modifier.fillMaxWidth()
            ) {
                Column(
                    modifier = Modifier.padding(16.dp),
                    horizontalAlignment = Alignment.CenterHorizontally
                ) {
                    if (currentQ.arabicDisplay.isNotEmpty()) {
                        Text(
                            text = currentQ.arabicDisplay,
                            fontSize = 32.sp,
                            fontWeight = FontWeight.Bold,
                            color = primaryGreen
                        )
                        Spacer(modifier = Modifier.height(8.dp))
                    }

                    Text(
                        text = currentQ.questionBn,
                        fontSize = 15.sp,
                        fontWeight = FontWeight.Bold,
                        color = themeColors.displayText,
                        textAlign = TextAlign.Center
                    )
                }
            }

            Spacer(modifier = Modifier.height(16.dp))

            // OPTIONS LIST
            Column(
                verticalArrangement = Arrangement.spacedBy(10.dp),
                modifier = Modifier.fillMaxWidth()
            ) {
                currentQ.optionsBn.forEachIndexed { optIdx, optionText ->
                    val isSelected = selectedIndex == optIdx
                    val isCorrect = optIdx == currentQ.correctIndex

                    val cardBg = when {
                        isSubmitted && isCorrect -> Color(0xFF059669).copy(alpha = 0.2f)
                        isSubmitted && isSelected && !isCorrect -> Color(0xFFDC2626).copy(alpha = 0.2f)
                        isSelected -> primaryGreen.copy(alpha = 0.12f)
                        else -> themeColors.cardBg
                    }

                    val borderColor = when {
                        isSubmitted && isCorrect -> Color(0xFF059669)
                        isSubmitted && isSelected && !isCorrect -> Color(0xFFDC2626)
                        isSelected -> primaryGreen
                        else -> themeColors.displayText.copy(alpha = 0.15f)
                    }

                    Surface(
                        shape = RoundedCornerShape(14.dp),
                        color = cardBg,
                        border = BorderStroke(1.dp, borderColor),
                        modifier = Modifier
                            .fillMaxWidth()
                            .clip(RoundedCornerShape(14.dp))
                            .clickable(enabled = !isSubmitted) {
                                selectedIndex = optIdx
                            }
                    ) {
                        Row(
                            modifier = Modifier.padding(14.dp),
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Box(
                                modifier = Modifier
                                    .size(24.dp)
                                    .clip(CircleShape)
                                    .background(if (isSelected) primaryGreen else Color.Transparent)
                                    .border(1.dp, if (isSelected) primaryGreen else themeColors.displayText.copy(alpha = 0.4f), CircleShape),
                                contentAlignment = Alignment.Center
                            ) {
                                if (isSelected) {
                                    Icon(imageVector = Icons.Default.Check, contentDescription = null, tint = Color.White, modifier = Modifier.size(14.dp))
                                }
                            }

                            Spacer(modifier = Modifier.width(12.dp))

                            Text(
                                text = optionText,
                                fontSize = 14.sp,
                                fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Normal,
                                color = themeColors.displayText
                            )
                        }
                    }
                }

                if (isSubmitted) {
                    Spacer(modifier = Modifier.height(6.dp))
                    Surface(
                        shape = RoundedCornerShape(12.dp),
                        color = primaryGreen.copy(alpha = 0.08f),
                        border = BorderStroke(1.dp, primaryGreen.copy(alpha = 0.2f)),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Row(
                            modifier = Modifier.padding(12.dp),
                            verticalAlignment = Alignment.Top
                        ) {
                            Icon(
                                imageVector = Icons.Default.Info,
                                contentDescription = null,
                                tint = primaryGreen,
                                modifier = Modifier
                                    .size(18.dp)
                                    .padding(top = 2.dp)
                            )
                            Spacer(modifier = Modifier.width(8.dp))
                            Text(
                                text = "ব্যাখ্যা: ${currentQ.explanationBn}",
                                fontSize = 12.sp,
                                color = themeColors.displayText,
                                lineHeight = 17.sp
                            )
                        }
                    }
                }
            }

            Spacer(modifier = Modifier.height(20.dp))

            // BOTTOM ACTION BUTTON
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(12.dp)
            ) {
                if (!isSubmitted) {
                    Button(
                        onClick = {
                            if (selectedIndex != null) {
                                isSubmitted = true
                                if (selectedIndex == currentQ.correctIndex) {
                                    score += 10
                                    correctCount += 1
                                }
                            }
                        },
                        enabled = selectedIndex != null,
                        colors = ButtonDefaults.buttonColors(
                            containerColor = primaryGreen,
                            contentColor = Color.White,
                            disabledContainerColor = primaryGreen.copy(alpha = 0.4f),
                            disabledContentColor = Color.White.copy(alpha = 0.6f)
                        ),
                        modifier = Modifier.fillMaxWidth(),
                        shape = RoundedCornerShape(14.dp)
                    ) {
                        Text(
                            text = if (isBn) "উত্তর নিশ্চিত করুন" else "Submit Answer",
                            fontSize = 14.sp,
                            fontWeight = FontWeight.Bold,
                            color = Color.White
                        )
                    }
                } else {
                    Button(
                        onClick = {
                            currentIndex += 1
                            selectedIndex = null
                            isSubmitted = false
                        },
                        colors = ButtonDefaults.buttonColors(containerColor = primaryGreen, contentColor = Color.White),
                        modifier = Modifier.fillMaxWidth(),
                        shape = RoundedCornerShape(14.dp)
                    ) {
                        Text(
                            text = if (currentIndex < sessionQuestions.size - 1) {
                                if (isBn) "পরবর্তী প্রশ্ন →" else "Next Question →"
                            } else {
                                if (isBn) "ফলাফল দেখুন" else "See Results"
                            },
                            fontSize = 14.sp,
                            fontWeight = FontWeight.Bold,
                            color = Color.White
                        )
                    }
                }
            }
        } else {
            // COMPLETED SUMMARY CARD
            Surface(
                shape = RoundedCornerShape(24.dp),
                color = themeColors.cardBg,
                border = BorderStroke(1.5.dp, primaryGreen),
                shadowElevation = 4.dp,
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(vertical = 20.dp)
            ) {
                Column(
                    modifier = Modifier.padding(24.dp),
                    horizontalAlignment = Alignment.CenterHorizontally
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(
                            imageVector = Icons.Default.CheckCircle,
                            contentDescription = null,
                            tint = primaryGreen,
                            modifier = Modifier.size(28.dp)
                        )
                        Spacer(modifier = Modifier.width(8.dp))
                        Text(text = "মাশাল্লাহ!", fontSize = 24.sp, fontWeight = FontWeight.Bold, color = primaryGreen)
                    }
                    Spacer(modifier = Modifier.height(8.dp))
                    Text(
                        text = if (isBn) "আপনি ১০টি প্রশ্নের কুইজ পর্ব সম্পন্ন করেছেন" else "You completed 10 quiz questions!",
                        fontSize = 14.sp,
                        color = themeColors.displayText,
                        textAlign = TextAlign.Center
                    )

                    Spacer(modifier = Modifier.height(16.dp))

                    Surface(
                        shape = RoundedCornerShape(16.dp),
                        color = primaryGreen.copy(alpha = 0.1f),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Column(
                            modifier = Modifier.padding(16.dp),
                            horizontalAlignment = Alignment.CenterHorizontally
                        ) {
                            Text(
                                text = "১০টির মধ্যে $correctCount টি সঠিক হয়েছে",
                                fontSize = 18.sp,
                                fontWeight = FontWeight.Bold,
                                color = primaryGreen
                            )
                            Spacer(modifier = Modifier.height(4.dp))
                            Text(
                                text = "মোট অর্জন: $score পয়েন্ট",
                                fontSize = 14.sp,
                                fontWeight = FontWeight.Medium,
                                color = themeColors.displayText
                            )
                        }
                    }

                    Spacer(modifier = Modifier.height(20.dp))

                    Button(
                        onClick = {
                            sessionSeed += 1
                            currentIndex = 0
                            score = 0
                            correctCount = 0
                            selectedIndex = null
                            isSubmitted = false
                        },
                        colors = ButtonDefaults.buttonColors(containerColor = primaryGreen, contentColor = Color.White),
                        modifier = Modifier.fillMaxWidth(),
                        shape = RoundedCornerShape(14.dp)
                    ) {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Icon(
                                imageVector = Icons.Default.Refresh,
                                contentDescription = null,
                                tint = Color.White,
                                modifier = Modifier.size(18.dp)
                            )
                            Spacer(modifier = Modifier.width(6.dp))
                            Text(
                                text = if (isBn) "নতুন ১০টি কুইজ শুরু করুন" else "Start New 10-Question Quiz",
                                fontSize = 14.sp,
                                fontWeight = FontWeight.Bold,
                                color = Color.White
                            )
                        }
                    }
                }
            }
        }
    }
}
